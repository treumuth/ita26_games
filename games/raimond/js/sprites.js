// ==================== SPRITES: characters, portraits, enemies, items ====================
const SHEETS = {};   // key -> [down, left, right, up]; each sheet is 4 frames: idle, step, passing, step
const HERO_NAMES = { Steven: 'steven', Caroline: 'caroline', Hitori: 'hitori', Uku: 'uku' };
const SHEET_DIRS = ['down', 'left', 'right', 'up'];
const loadImg = src => { const im = new Image(); im.src = src; return im };
function loadSheet(key) { SHEETS[key] = SHEET_DIRS.map(d => loadImg('assets/sprites/' + key + '_' + d + '.png')) }
CH.forEach(c => { c.key = HERO_NAMES[c.n]; loadSheet(c.key) });
Object.entries(ND).forEach(([id, c]) => { c.key = 'npc_' + id; loadSheet(c.key) });
const ready = im => im && im.complete && im.naturalWidth > 0;

// f: 0 = standing (gentle breathing), 1..4 = walk-cycle frame. feet at (x,y). c.g = ghost alpha.
function drawChar(c, x, y, d = 0, f = 0, s = 1, flip = false) {
  const sheet = c.key && SHEETS[c.key], img = sheet && sheet[Math.max(0, Math.min(3, d))];
  if (!ready(img)) return;
  const fw = img.naturalWidth / 4, fh = img.naturalHeight, ph = ((c.n || '').length * 13) | 0;
  const fi = f > 0 ? (f - 1) % 4 : (((tick + ph) >> 5) & 1 ? 2 : 0);
  const fy = c.g != null ? Math.round(-3 + Math.sin(tick / 14) * 2) : 0, keepA = X.globalAlpha;
  ell(x, y - 1, Math.round(fw * .36 * s), 2, 'rgba(20,10,30,.3)');
  if (c.g != null) X.globalAlpha *= c.g; X.imageSmoothingEnabled = false;
  if (flip) { X.save(); X.translate(Math.round(x), 0); X.scale(-1, 1); X.drawImage(img, fi * fw, 0, fw, fh, Math.round(-fw * s / 2), Math.round(y - fh * s + fy + 1), Math.round(fw * s), Math.round(fh * s)); X.restore() }
  else X.drawImage(img, fi * fw, 0, fw, fh, Math.round(x - fw * s / 2), Math.round(y - fh * s + fy + 1), Math.round(fw * s), Math.round(fh * s));
  X.globalAlpha = keepA;
}
// ---- portraits (hero art supplied by you, NPC art generated by tools/make_assets.py)
const PORTRAITS = {};
const PFILE = e => ({ laugh: 'happy', smug: 'dark', scared: 'worried' })[e] || e;
for (const who of ['caroline', 'hitori', 'steven', 'uku', ...Object.keys(ND).map(i => 'npc_' + i)])
  for (const emo of ['neutral', 'happy', 'laugh', 'sad', 'angry', 'shock', 'scared', 'worried', 'blush', 'dark', 'smug']) PORTRAITS[who + ':' + emo] = loadImg('assets/portraits/' + who + '_' + PFILE(emo) + '.png');
const portraitKey = c => c.key && c.key.startsWith('npc_') ? c.key : (c.n || '').toLowerCase();
function portrait(c, emo, x, y, s) {   // draws a 56-unit-wide portrait at (x,y) in the current layer
  const art = PORTRAITS[portraitKey(c) + ':' + (emo || 'neutral')] || PORTRAITS[portraitKey(c) + ':neutral'];
  if (!ready(art)) { r(x, y, 56 * s, 56 * s, '#222'); return }
  X.globalAlpha = c.g || 1; X.imageSmoothingEnabled = true; X.imageSmoothingQuality = 'high';
  X.drawImage(art, x, y, 56 * s, 56 * s * art.naturalHeight / art.naturalWidth); X.imageSmoothingEnabled = false; X.globalAlpha = 1;
}
// ---- enemies: small overworld sprite + big battle sprite
const ENIMG = {}; Object.values(EN).forEach(e => { ENIMG[e.spr] = { small: loadImg('assets/enemies/' + e.spr + '_small.png'), big: loadImg('assets/enemies/' + e.spr + '_big.png') } });
function drawEnemy(kind, x, y, s = 1, big = false, wob = true) {   // feet at (x,y)
  const im = ENIMG[EN[kind].spr][big ? 'big' : 'small']; if (!ready(im)) return;
  const w = Math.round(im.naturalWidth * s), h = Math.round(im.naturalHeight * s), b = wob ? Math.round(Math.sin(tick / 9) * (big ? 3 : 1)) : 0;
  if (!big) ell(x, y - 1, Math.round(w * .35), 2, 'rgba(20,10,30,.3)');
  X.imageSmoothingEnabled = false; X.drawImage(im, Math.round(x - w / 2), Math.round(y - h + b), w, h);
}
// ---- items (black with white outlines): 32px sprite + 96px portrait
const ITIMG = {}; Object.keys(ITEMDEF).forEach(k => { ITIMG[k] = { spr: loadImg('assets/items/' + k + '.png'), por: loadImg('assets/items/' + k + '_portrait.png') } });
function drawItem(id, x, y, s = .5, por = false) {   // UI layer: s=.5 -> 16 UI units for the sprite
  const im = ITIMG[id] && ITIMG[id][por ? 'por' : 'spr']; if (!ready(im)) return; X.imageSmoothingEnabled = false; X.drawImage(im, Math.round(x * U) / U, Math.round(y * U) / U, im.naturalWidth * s, im.naturalHeight * s);
}

// ---- collectible sprites (glints + a soft pulse so you can tell what is worth picking up)
const PICK = {}; ['mushroom', 'key', 'shell', 'token', 'snack', 'marble', 'boot', 'oil', 'shard', 'cone', 'wax', 'page'].forEach(k => PICK[k] = loadImg('assets/pickups/' + k + '.png'));
function drawPick(kind, x, y, strong) {   // feet at (x,y), world layer
  const im = PICK[kind], b = Math.round(Math.sin(tick / 10 + x) * 2); ell(x, y, 6, 2, 'rgba(0,0,0,.25)');
  ell(x, y - 9 + b, 9 + Math.round(Math.sin(tick / 14 + y) * 1.5), 8, strong ? 'rgba(255,255,210,.15)' : 'rgba(255,255,210,.07)');
  if (ready(im)) { X.imageSmoothingEnabled = false; X.drawImage(im, Math.round(x - im.naturalWidth / 2), Math.round(y - im.naturalHeight - 1 + b)) }
  for (let i = 0; i < (strong ? 3 : 2); i++) { const ph = (tick * .8 + i * 37 + x * 3) % 90; if (ph < 24) { const k = ph < 12 ? ph / 12 : (24 - ph) / 12, ox = [-9, 8, 1][i], oy = [-15, -11, -20][i], a = Math.round(k * 2.6) + 1; r(x + ox - a, y + oy + b, a * 2 + 1, 1, '#fff'); r(x + ox, y + oy - a + b, 1, a * 2 + 1, '#fff') } }
}
